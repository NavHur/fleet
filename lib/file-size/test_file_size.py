import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from file_size import LIMIT_BYTES  # noqa: E402

BIG = "x" * (LIMIT_BYTES + 1)
SMALL = "small\n"


class Repo:
    def __init__(self, path):
        self.path = path
        self.git("init", "-q", "-b", "main")
        self.git("config", "user.email", "test@example.com")
        self.git("config", "user.name", "Test")

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.path, check=True, capture_output=True)

    def write(self, name, text):
        (self.path / name).parent.mkdir(parents=True, exist_ok=True)
        (self.path / name).write_text(text)

    def commit(self, **files):
        for name, text in files.items():
            self.write(name, text)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "commit")

    def run(self, *args):
        return subprocess.run([sys.executable, str(ROOT / "file_size.py"), *args], cwd=self.path,
                              text=True, capture_output=True)


class FileSizeTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Repo(Path(self.tmp.name))

    def tearDown(self):
        self.tmp.cleanup()

    def stage(self, **files):
        for name, text in files.items():
            self.repo.write(name, text)
        self.repo.git("add", "-A")

    def test_new_file_over_the_cap_fails_with_split_advice(self):
        self.repo.commit(**{"a.py": SMALL})
        self.stage(**{"big.py": BIG})
        result = self.repo.run("check", "--staged")
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"big.py: {LIMIT_BYTES + 1:,} bytes, new", result.stdout)
        self.assertIn("Split each file above along a seam", result.stdout)

    def test_first_commit_is_checked(self):
        self.stage(**{"big.py": BIG})
        self.assertEqual(self.repo.run("check", "--staged").returncode, 1)

    def test_file_at_the_cap_passes(self):
        self.stage(**{"edge.py": "x" * LIMIT_BYTES})
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)

    def test_over_cap_file_that_grows_fails(self):
        self.repo.commit(**{"big.py": BIG})
        self.stage(**{"big.py": BIG + "more\n"})
        result = self.repo.run("check", "--staged")
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"was {LIMIT_BYTES + 1:,}", result.stdout)

    def test_over_cap_file_that_does_not_grow_passes_with_a_warning(self):
        self.repo.commit(**{"big.py": BIG})
        self.stage(**{"big.py": "y" * (LIMIT_BYTES + 1)})
        result = self.repo.run("check", "--staged")
        self.assertEqual(result.returncode, 0)
        self.assertIn("did not grow", result.stdout)

    def test_renamed_over_cap_file_is_not_new(self):
        self.repo.commit(**{"old.py": BIG})
        self.repo.git("mv", "old.py", "new.py")
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)

    def test_lockfiles_binaries_and_marked_files_are_skipped(self):
        self.repo.commit(**{".gitattributes": "gen/** linguist-generated\nthird/** linguist-vendored=true\n"})
        self.stage(**{"pnpm-lock.yaml": BIG, "app.min.js": BIG, "gen/api.ts": BIG, "third/lib.js": BIG})
        (self.repo.path / "image.bin").write_bytes(b"\0" + BIG.encode())
        self.repo.git("add", "-A")
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)

    def test_each_lockfile_name_is_skipped(self):
        names = ("npm-shrinkwrap.json", "packages.lock.json", "gradle.lockfile", "Package.resolved")
        self.stage(**{name: BIG for name in names})
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)

    def test_a_generated_code_marker_in_the_first_lines_skips_the_file(self):
        self.stage(**{"api.go": f"// Code generated by x. DO NOT EDIT.\n{BIG}",
                      "types.py": f"import x\n# @generated\n{BIG}"})
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)
        self.assertIn("No file over", self.repo.run("report").stdout)

    def test_a_generated_code_marker_below_the_first_lines_does_not_skip_the_file(self):
        self.stage(**{"api.go": "y\n" * 5 + f"// Code generated by x. DO NOT EDIT.\n{BIG}"})
        result = self.repo.run("check", "--staged")
        self.assertEqual(result.returncode, 1)
        self.assertIn("api.go", result.stdout)

    def test_tracked_mode_sees_unstaged_growth(self):
        self.repo.commit(**{"a.py": SMALL})
        self.repo.write("a.py", BIG)
        self.assertEqual(self.repo.run("check", "--staged").returncode, 0)
        self.assertEqual(self.repo.run("check", "--tracked").returncode, 1)

    def test_base_mode_compares_against_the_merge_base(self):
        self.repo.commit(**{"a.py": SMALL})
        self.repo.git("checkout", "-q", "-b", "feature")
        self.repo.commit(**{"big.py": BIG})
        self.repo.git("checkout", "-q", "main")
        self.repo.commit(**{"later.py": SMALL})
        self.repo.git("checkout", "-q", "feature")
        result = self.repo.run("check", "--base", "main")
        self.assertEqual(result.returncode, 1)
        self.assertIn("big.py", result.stdout)

    def test_submodule_pointer_bump_is_not_a_file(self):
        with tempfile.TemporaryDirectory() as origin:
            Repo(Path(origin)).commit(**{"lib.py": SMALL})
            self.repo.commit(**{"a.py": SMALL})
            self.repo.git("-c", "protocol.file.allow=always", "submodule", "add", origin, "sub")
            self.repo.git("commit", "-q", "-m", "add submodule")
            self.repo.git("-C", "sub", "-c", "user.email=t@example.com", "-c", "user.name=T",
                          "commit", "-q", "--allow-empty", "-m", "bump")
            self.repo.git("add", "sub")
            self.assertEqual(self.repo.run("check", "--staged").returncode, 0)
            self.assertEqual(self.repo.run("check", "--tracked").returncode, 0)
            self.repo.git("commit", "-q", "-m", "bump")
            self.assertEqual(self.repo.run("check", "--base", "HEAD~1").returncode, 0)

    def test_tracked_symlink_is_measured_by_its_link_text(self):
        self.repo.commit(**{"a.py": SMALL})
        os.symlink("a.py", self.repo.path / "link")
        self.repo.git("add", "link")
        self.repo.git("commit", "-q", "-m", "link")
        (self.repo.path / "link").unlink()
        os.symlink(str(self.repo.path), self.repo.path / "link")
        self.assertEqual(self.repo.run("check", "--tracked").returncode, 0)

    def test_unknown_base_is_a_usage_error(self):
        self.repo.commit(**{"a.py": SMALL})
        self.assertEqual(self.repo.run("check", "--base", "nope").returncode, 2)

    def test_report_lists_tracked_files_over_the_cap(self):
        self.repo.commit(**{"big.py": BIG, "a.py": SMALL, "yarn.lock": BIG})
        result = self.repo.run("report")
        self.assertEqual(result.stdout.strip(), f"big.py: {LIMIT_BYTES + 1:,} bytes")


if __name__ == "__main__":
    unittest.main()
