"""Steps bin/sync runs after third-party skills are installed or updated.

    python3 post_install.py BACKUP_DIR [--apply]

1. Codex ignores `disable-model-invocation: true` in SKILL.md frontmatter and
   reads `policy.allow_implicit_invocation` from agents/openai.yaml instead.
   Give every installed skill that sets the former, and ships no openai.yaml,
   one that says the same thing, so Codex matches Claude Code and Cursor.
   Updates replace skill folders, so this runs on every sync.
2. Write ~/.config/principles.md: one line per principle-* skill, from pstack
   or from this repo, saying when it applies and where its SKILL.md is.
3. Write config/instructions.md and a pointer to that index into each
   agent's global instructions, inside a marked block this script owns.
   When this host has hosts/<host>/instructions.md or
   instructions.<agent>.md, they become the text above the block, in that
   order; otherwise the text outside the block is left as the host's own.

Prints one plan line per change, in bin/sync's format. With --apply, copies
each instruction file into BACKUP_DIR before changing it.
"""
from pathlib import Path
import re
import shutil
import sys

HOME = Path.home()
SKILLS = HOME / ".agents" / "skills"
INDEX = HOME / ".config" / "principles.md"
INSTRUCTIONS = {
    "claude": HOME / ".claude" / "CLAUDE.md",
    "codex": HOME / ".codex" / "AGENTS.md",
    "opencode": HOME / ".config" / "opencode" / "AGENTS.md",
}
HOST_CONF = HOME / ".config" / "fleet" / "host.json"  # bin/sync links it to hosts/<host>/host.json
CODEX_META = """\
# Written by fleet bin/sync: SKILL.md sets disable-model-invocation, which
# Codex ignores. This keeps Codex from invoking the skill on its own.
policy:
  allow_implicit_invocation: false
"""
SHARED = Path(__file__).resolve().parents[2] / "config" / "instructions.md"
BLOCK_START = "<!-- fleet:instructions (managed by fleet bin/sync from config/instructions.md) -->"
BLOCK_END = "<!-- /fleet:instructions -->"
PRINCIPLES = """## Engineering principles

Before nontrivial design, implementation, debugging, or review, read
`~/.config/principles.md` and apply the principles that fit, reading each one's
SKILL.md in full first. In `code-review`, add the matching principles to the
Standards sources, ranked below the repo's documented standards.
"""
# The block's earlier name; its contents now live in the instructions block.
RETIRED_BLOCK = re.compile(r"<!-- fleet:principles .*?<!-- /fleet:principles -->\n?", re.S)
BLOCK = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?", re.S)


def short(path):
    path = str(path)
    return "~/" + path[len(str(HOME)) + 1:] if path.startswith(str(HOME) + "/") else path


def say(verb, text):
    print(f"  {verb:<10} {text}")


def frontmatter(skill_dir):
    try:
        text = (skill_dir / "SKILL.md").read_text()
    except (FileNotFoundError, NotADirectoryError):
        return {}
    match = re.match(r"---\n(.*?)\n---", text, re.S)
    fields = {}
    for line in (match.group(1) if match else "").splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "\t")):
            fields[key.strip()] = value.strip().strip('"').strip("'")
    return fields


def installed():
    """Third-party skills: real folders in ~/.agents/skills (own skills are symlinks)."""
    if not SKILLS.is_dir():
        return []
    return sorted(p for p in SKILLS.iterdir() if p.is_dir() and not p.is_symlink())


def backup(path, backup_dir):
    if path.exists():
        saved = backup_dir / path.relative_to(HOME)
        saved.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, saved)


def codex_meta(apply):
    for skill in installed():
        meta = skill / "agents" / "openai.yaml"
        if frontmatter(skill).get("disable-model-invocation") == "true" and not meta.exists():
            say("codex-meta", f"{skill.name}: not implicitly invoked")
            if apply:
                meta.parent.mkdir(exist_ok=True)
                meta.write_text(CODEX_META)


def index_text():
    lines = [
        "<!-- Generated by fleet bin/sync from the installed principle-* skills. -->",
        "",
        "# Engineering principles",
        "",
        "Each line says when a principle applies and where its SKILL.md is. Read the",
        "file in full before applying the principle.",
        "",
    ]
    # Own principles are symlinks from this repo, so list every folder.
    for skill in sorted(SKILLS.glob("principle-*")):
        if skill.is_dir():
            description = frontmatter(skill).get("description", "")
            lines.append(f"- **{skill.name[len('principle-'):]}**: {description} "
                         f"`~/.agents/skills/{skill.name}/SKILL.md`")
    return "\n".join(lines) + "\n"


def write_index(apply, backup_dir):
    text = index_text()
    if text.count("\n- **") == 0 and not INDEX.exists():
        return  # no principles installed yet
    if INDEX.exists() and INDEX.read_text() == text:
        return
    say("write", short(INDEX))
    if apply:
        backup(INDEX, backup_dir)
        INDEX.parent.mkdir(parents=True, exist_ok=True)
        INDEX.write_text(text)


def with_block(text, block):
    """The text with the managed block in place of the current or retired one, else appended."""
    for pattern in (BLOCK, RETIRED_BLOCK):
        if pattern.search(text):
            return pattern.sub(lambda _: block, text, count=1)
    if not text:
        return block
    return text + ("\n" if text.endswith("\n") else "\n\n") + block


def host_text(host_dir, agent):
    """This host's text for the agent, or None when the host leaves it unmanaged."""
    parts = [f.read_text().strip() for f in (host_dir / "instructions.md", host_dir / f"instructions.{agent}.md")
             if f.is_file()]
    return "\n\n".join(parts) + "\n\n" if parts else None


def with_host(text, host):
    """The text with everything above the managed block replaced by the host's text."""
    start = text.find(BLOCK_START)
    return host + text[start:] if start >= 0 else host + text


def instructions(apply, backup_dir):
    block = f"{BLOCK_START}\n{SHARED.read_text().rstrip()}\n\n{PRINCIPLES}{BLOCK_END}\n"
    host_dir = HOST_CONF.resolve().parent if HOST_CONF.exists() else None
    for agent, path in INSTRUCTIONS.items():
        if not path.parent.is_dir():
            continue
        text = path.read_text() if path.exists() else ""
        updated = with_block(text, block)
        host = host_text(host_dir, agent) if host_dir else None
        if host is not None:
            updated = with_host(updated, host)
        if updated == text:
            continue
        source = f"hosts/{host_dir.name} and config/instructions.md" if host is not None else "config/instructions.md"
        say("instruct", f"{short(path)}: instructions from {source}")
        if apply:
            backup(path, backup_dir)
            path.write_text(updated)


def main(argv):
    backup_dir, apply = Path(argv[0]), "--apply" in argv
    codex_meta(apply)
    write_index(apply, backup_dir)
    instructions(apply, backup_dir)


if __name__ == "__main__":
    main(sys.argv[1:])
